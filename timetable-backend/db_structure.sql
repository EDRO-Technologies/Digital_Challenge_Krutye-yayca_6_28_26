-- Функция для обновления нагрузки
create or replace function update_workload_hours()
returns trigger as $$
declare
  -- Определяем длительность пары в академических часах (обычно 2 часа)
  -- Можно усложнить и считать разницу start_time/end_time, но для MVP хватит константы
  ac_hours int := 2; 
  is_cancelled boolean;
begin
  -- 1. ПРИ СОЗДАНИИ ПАРЫ (INSERT)
  if (TG_OP = 'INSERT') then
    -- Если пара активна (не отменена), вычитаем часы
    if NEW.status = (select id from schedule_item_statuses where name = 'Активно' limit 1) then
      update teacher_workload
      set planned_hours = planned_hours - ac_hours
      where teacher_id = NEW.speaker_id 
        and subject_id = NEW.subject_id
        and start_year = extract(year from NEW.start_time)::int; -- Упрощаем год
    end if;
    return NEW;
  end if;

  -- 2. ПРИ ОБНОВЛЕНИИ (UPDATE)
  if (TG_OP = 'UPDATE') then
    -- Получаем ID статуса "отменено"
    is_cancelled := (NEW.status = (select id from schedule_item_statuses where name = 'Отменено' limit 1));
    
    -- Сценарий А: Пару ОТМЕНИЛИ (была активна -> стала cancelled)
    if OLD.status != NEW.status and is_cancelled then
      update teacher_workload
      set planned_hours = planned_hours + ac_hours
      where teacher_id = NEW.speaker_id 
        and subject_id = NEW.subject_id;
    end if;

    -- Сценарий Б: Пару ВОССТАНОВИЛИ (была cancelled -> стала active)
    if OLD.status != NEW.status and not is_cancelled then
      update teacher_workload
      set planned_hours = planned_hours - ac_hours
      where teacher_id = NEW.speaker_id 
        and subject_id = NEW.subject_id;
    end if;
    
    return NEW;
  end if;

  return null;
end;
$$ language plpgsql;

-- Создаем триггер
create trigger trg_update_workload
after insert or update on schedule_items
for each row
execute function update_workload_hours();


