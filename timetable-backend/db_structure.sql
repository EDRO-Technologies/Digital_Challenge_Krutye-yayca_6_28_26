create table schedule_items (
  id bigint generated by default as identity primary key,
  
  -- Связи
  subject_id bigint references subjects(id),
  speaker_id bigint references users(id), -- Тот, кто ведет лекцию / мероприятие
  room_id bigint references rooms(id),
  
  -- Группировка (важно для Excel!)
  group_id bigint references groups(id), -- Каждая запись Excel привязана к группе
  subgroup int, -- NULL = вся группа, 1 = первая подгруппа, 2 = вторая
  
  -- Время
  start_time timestamp with time zone not null,
  end_time timestamp with time zone not null,

  -- Детали
  title text, -- название мероприятия / тип пары ('лек', 'пр', 'лаб')
  description text, -- "Защита лабораторных", "Будет в Teams"
  is_lesson boolean default true, -- false для мероприятий
  
  status bigint references schedule_item_statuses(id),
  updated_at timestamp with time zone default now(),
  created_at timestamp with time zone default now()
);

