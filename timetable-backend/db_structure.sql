create table teacher_workload (
  id bigint generated by default as identity primary key,
  teacher_id bigint references users(id) on delete cascade,
  subject_id bigint references subjects(id) on delete cascade,
  
  -- Нагрузка (в академических часах)
  planned_hours int not null check (planned_hours > 0),
  
  -- Период: храним только год начала (например, 2025)
  start_year int not null check (start_year > 2020 and start_year < 2100),
  semester int not null check (semester in (1, 2)), 
  
  -- Составной ключ
  unique(teacher_id, subject_id, start_year, semester)
);

